marks = []

for a in range(6):
    m = int(input("Enter marks: "))
    marks.append(m)

marks.sort()

print("Sorted marks:", marks)
#for → starts a loop.
#a → variable that changes each time.
#range(6) → gives numbers 0 to 5, so the loop runs 6 times.
#: → tells Python that the indented code below belongs to this loop.



